-- ============================================================================
-- Second source, step 1: load the drawings and capability sheets, audit the parse
-- ============================================================================
-- Hartmann Gusstechnik closes its foundry. 40 cast parts are single-sourced
-- there. Before ranking anyone, the buyer checks that every requirement and
-- every capability was read the way a person reads it. A supplier that "fails"
-- because we misread the drawing is worse than no ranking at all.
--
-- The loader (sql/load.sql) reads numbers with parse_quantity and codes
-- (grades, PN, EN 10204 certificates) with SQL normalisers, then builds one
-- property tree per part and per supplier with one item per capability class.
--
-- Data: examples/second_source/data (generated by
--   cd scripts && uv run python -m scripts.examples.second_source)
-- Run:  DATAZOO_DISABLE_TELEMETRY=1 ./build/release/duckdb < examples/second_source/01_parse_audit.sql
-- ============================================================================

.read examples/second_source/sql/load.sql

.print '>>> 1. What arrived'
SELECT (SELECT count(*) FROM parts) AS parts,
       (SELECT count(*) FROM part_requirements) AS requirement_rows,
       (SELECT count(*) FROM suppliers) AS vendor_records,
       (SELECT count(*) FROM supplier_capabilities) AS capability_rows;
-- Expected:
--   parts | requirement_rows | vendor_records | capability_rows
--   40    | 231              | 15             | 111

.print ''
.print '>>> 2. Wordings without a capability class (not checked at all)'
-- attribute_vocabulary maps every wording (DE and EN) to a class. A wording that
-- is not in it is silently not compared, so list it and decide.
SELECT side, name, count(*) AS n_rows, string_agg(DISTINCT value_text, ' | ') AS values
FROM spec_texts WHERE class_id IS NULL
GROUP BY ALL ORDER BY name;
-- Expected:
--   part | Härte           | 2 | 180-220 HB
--   part | Wärmebehandlung | 2 | spannungsarm geglüht
-- Hardness and heat treatment are not on any capability sheet: check them by
-- hand on the RFQ, or add a class and ask the foundries for the value.

.print ''
.print '>>> 3. Why codes do not go through parse_quantity'
-- What the parser makes of the code texts on the drawings. It refuses designations
-- and certificate numbers (empty result) and reads PN as a category; only
-- "3.1 acc. to EN 10204" still comes back as a number, with the next word as unit.
SELECT t.class_id,
       CASE WHEN p.category IS NOT NULL THEN 'category ' || p.category
            WHEN p.dimension IS NOT NULL THEN 'number ' || p.lo || ', dimension ' || p.dimension
            WHEN p.lo IS NOT NULL THEN 'number ' || p.lo || ', unknown unit ' || p.unit
            ELSE 'empty (refused)' END AS parse_quantity_says,
       count(*) AS n, min(t.value_text) AS example
FROM spec_texts t, LATERAL (SELECT parse_quantity(t.value_text, t.lang) AS p)
WHERE t.side = 'part' AND t.class_id IN ('material_grade', 'cert_level', 'pressure_class')
GROUP BY ALL ORDER BY t.class_id, parse_quantity_says;
-- Expected:
--   cert_level     | empty (refused)              | 25 | Abnahmeprüfzeugnis 3.1 nach EN 10204
--   cert_level     | number 3.1, unknown unit acc |  5 | 3.1 acc. to EN 10204
--   cert_level     | number 3.2, unknown unit acc |  3 | 3.2 acc. to EN 10204
--   material_grade | empty (refused)              | 40 | EN-GJL-250
--   pressure_class | category PN10                |  2 | PN 10
--   pressure_class | category PN16                |  2 | PN 16
--   pressure_class | category PN25                |  1 | PN 25
--   pressure_class | category PN40                |  1 | PN 40
-- The remaining numbers get the next word as unit ("acc"), so they can only ever
-- be gates, never a passed check.
-- A certificate level is an ordinal code, not a count: the loader reads it with a
-- regex and writes category EN10204-3.1 with dimension cert_level.

.print ''
.print '>>> 4. The normalisers on the planted traps'
SELECT side, value_text, string_agg(DISTINCT category, ', ' ORDER BY category) AS normalised
FROM spec_values
WHERE value_text IN ('GGG-50', 'EN-GJS-400-18', 'Werkszeugnis 2.2', 'PN 16', 'PN16')
   OR (side = 'supplier' AND owner_id = 'SUP-BALTIC' AND class_id = 'material_grade')
GROUP BY ALL ORDER BY side, value_text;
-- Expected:
--   part     | EN-GJS-400-18    | GJS-400        (elongation dropped; -18 is the low-temperature variant)
--   part     | GGG-50           | GJS-500        (old DIN 1693 name)
--   part     | PN 16            | PN16
--   part     | Werkszeugnis 2.2 | EN10204-2.2
--   supplier | EN-GJL-200 bis EN-GJL-300; EN-GJS-400 bis EN-GJS-450 | GJL-200, GJL-250, GJL-300, GJS-400, GJS-450
--   supplier | PN 16            | PN16
--   supplier | PN16             | PN16
-- A range of grades on a capability sheet becomes one value per standard grade:
-- the kernel takes the best of a supplier's values, so they read as "any of".

.print ''
.print '>>> 5. Numbers: units, thousands separators, every value with a dimension'
SELECT side, class_id, count(*) AS n_values, count(*) FILTER (WHERE dimension IS NULL) AS no_dimension,
       string_agg(DISTINCT source_units, ' ') AS units_seen
FROM (SELECT v.*, coalesce(parse_quantity(v.value_text, 'de').source_unit, '-') AS source_units
      FROM spec_values v WHERE v.class_id IN ('piece_weight', 'lot_size'))
GROUP BY ALL ORDER BY side, class_id;
-- Expected:
--   part     | lot_size     | 40 | 0 | (Stk, pcs)
--   part     | piece_weight | 42 | 0 | (kg, t)
--   supplier | lot_size     | 14 | 0 | (Stk, pcs)
--   supplier | piece_weight | 14 | 0 | (kg, t)
SELECT value_text, lo AS kg FROM spec_values
WHERE side = 'supplier' AND class_id = 'piece_weight' AND owner_id IN ('SUP-BRANDT', 'SUP-BRANDT2', 'SUP-NORDGUSS')
ORDER BY owner_id;
-- Expected:
--   max. 1.800 kg | 1800.0   (German thousands separator)
--   bis 1,8 t     | 1800.0
--   bis 5 t       | 5000.0

.print ''
.print '>>> 6. Direction: the class decides, not the wording on the drawing'
-- "max. Stückgewicht 38 kg" describes the part. For sourcing it means the foundry
-- must pour AT LEAST 38 kg. The loader takes bound from capability_classes and
-- keeps the drawing's word only for this audit.
SELECT v.class_id, v.stated_bound AS drawing_says, c.bound AS class_needs, count(*) AS n
FROM spec_values v JOIN capability_classes c USING (class_id)
WHERE v.side = 'part' AND c.kind = 'numeric' AND v.stated_bound IS NOT NULL
GROUP BY ALL ORDER BY ALL;
-- Expected:
--   piece_weight | at_most | at_least | 33
--   tolerance    | at_most | at_most  | 13
-- 33 weight lines say "max." and mean the opposite of what sourcing needs. Taking
-- the parsed bound would have turned every heavier-is-better check upside down.

.print ''
.print '>>> 7. Gates before ranking'
-- (a) category values without a dimension. The kernel looks rules up by
--     dimension; material_grade has none in capability_classes (left blank).
--     Harmless here: grades are nominal (no rules) and each class is its own
--     item, so a grade is only compared with grades. It would matter for PN.
SELECT 'category without dimension' AS check, class_id, count(*) AS n
FROM (SELECT class_id FROM spec_values v JOIN capability_classes c USING (class_id)
      WHERE v.category IS NOT NULL AND c.dimension IS NULL)
GROUP BY ALL;
-- Expected:
--   category without dimension | material_grade | 128
-- (b) validate_trees finds no structural problem; note that it does NOT warn about
--     the 128 category values above.
SELECT (SELECT count(*) FROM validate_trees('part_nodes', 'part_attributes')) AS part_tree_issues,
       (SELECT count(*) FROM validate_trees('supplier_nodes', 'supplier_attributes')) AS supplier_tree_issues;
-- Expected: 0 | 0
-- (c) parts with two lines for one class (an English copy of a German line)
SELECT owner_id AS part_id, class_id, list(value_text ORDER BY row_id) AS lines
FROM spec_values WHERE side = 'part' AND class_id = 'piece_weight'
GROUP BY ALL HAVING count(*) > 1 ORDER BY part_id;
-- Expected:
--   P-1009 | piece_weight | ['ca. 6,5 kg', max. 6.5 kg]
--   P-1027 | piece_weight | [max. 13.9 kg, max. 13.9 kg]
-- Both lines stay as two attributes of one item: both must be met, so a copy is harmless.

.print ''
.print '>>> 8. Vendor master: one record per foundry'
SELECT m.master_id, list(s.name ORDER BY s.supplier_id) AS vendor_records
FROM supplier_master m JOIN suppliers s USING (supplier_id)
GROUP BY m.master_id HAVING count(*) > 1;
-- Expected:
--   SUP-BRANDT | [Gießerei Brandt GmbH, Giesserei Brandt]
SELECT status, count(*) AS vendor_records FROM supplier_master
WHERE supplier_id = master_id GROUP BY ALL ORDER BY status;
-- Expected:
--   approved     | 12
--   exiting      | 1    (Hartmann, the one we are replacing)
--   not_approved | 1    (Novaguss: capable, but no supplier audit yet)
